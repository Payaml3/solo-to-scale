"""Generate the agent files for both tools from roles/*.yaml, the only source.

  python scripts/sync_agents.py          # write agents/claude/*.md and agents/codex/*.toml
  python scripts/sync_agents.py --check  # exit 1 if any generated file differs from its source

Roles with `enabled: false` (the sales advisor) go to templates/agents-optional/ instead, so the
plugin never loads them; init copies them into a repo when the founder enables them.
Model names come from models.yaml by tier. Standard library only.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import s2s_yaml  # noqa: E402

PLUGIN = Path(__file__).resolve().parents[1]
CLAUDE_TOOLS = {
    "edit": "Read, Grep, Glob, Edit, Write, Bash",
    "research": "Read, Grep, Glob, WebSearch, WebFetch",
    "read-only": "Read",
}
CODEX_SANDBOX = {"edit": "workspace-write", "research": "read-only", "read-only": "read-only"}
ACCESS_TEXT = {
    "edit": "Edit, test and git in this repository only. No production secrets.",
    "research": "Web search and read-only repository access. No production secrets.",
    "read-only": "Read the one-page decision brief only. No repository access, no web, no secrets.",
}
REQUIRED = ("name", "title", "kind", "enabled", "description", "tier", "effort", "access")


def header(role: str, comment: str) -> str:
    return f"{comment} Generated by solo-to-scale; edit `roles/{role}.yaml`, then run scripts/sync_agents.py."


def bullets(items: list[str] | None) -> list[str]:
    return [f"- {x}" for x in items or []]


def body(r: dict) -> str:
    out = [f"# {r['title']}", ""]
    if r["kind"] == "team":
        out += [r["mission"], ""]
        for key, head in (("owns", "Owns"), ("skills", "Skills"), ("model", "Model"),
                          ("inputs", "Reads"), ("outputs", "Writes"), ("approval", "Needs the founder's approval for")):
            out += [f"## {head}", *bullets(r.get(key)), ""]
        out += ["## Tools", ACCESS_TEXT[r["access"]], "", "## Never", *bullets(r.get("never")), ""]
        out += ["## Rules",
                "- One role per session. Talk to other roles only through issues, PRs, the registers and HANDOFF.md.",
                "- A role proposes; the founder approves. New content starts as Proposed, Assumption or Open.",
                "- Read narrowly: never read a whole file over 150 lines; use grep -n and line ranges."]
    else:
        out += [f"You advise the founder through the {r['lens']} lens. You pull toward {r['pulls_toward']}.",
                "You have no vote; the founder chairs and decides.", "",
                "## Draws on", r["draws_on"], "", "## Asks", *bullets(r.get("asks")), "",
                "## Memo", r["memo"], "", "## Tools", ACCESS_TEXT[r["access"]], "",
                "## Rules", *bullets(r.get("rules"))]
    return "\n".join(out).rstrip() + "\n"


def claude_md(r: dict, models: dict) -> str:
    fm = ["---", f"name: {r['name']}", f"description: {r['description']}",
          f"tools: {CLAUDE_TOOLS[r['access']]}", f"model: {models['claude'][r['tier']]}", "---"]
    return "\n".join(fm) + "\n" + header(r["name"], "<!--") + " -->\n\n" + body(r)


def toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def codex_toml(r: dict, models: dict) -> str:
    text = body(r)
    if "'''" in text:
        raise ValueError(f"{r['name']}: body may not contain '''")
    return "\n".join([
        header(r["name"], "#"),
        f"name = {toml_str(r['name'])}",
        f"description = {toml_str(r['description'])}",
        f"model = {toml_str(models['codex'][r['tier']])}",
        f"model_reasoning_effort = {toml_str(r['effort'])}",
        f"sandbox_mode = {toml_str(CODEX_SANDBOX[r['access']])}",
        "developer_instructions = '''",
        text.rstrip("\n"),
        "'''",
    ]) + "\n"


def load_roles(plugin: Path = PLUGIN) -> list[dict]:
    roles = []
    for path in sorted((plugin / "roles").glob("*.yaml")):
        r = s2s_yaml.load(path)
        missing = [k for k in REQUIRED if r.get(k) in (None, "")]
        if missing:
            raise ValueError(f"{path.name}: missing {', '.join(missing)}")
        if r["name"] != path.stem:
            raise ValueError(f"{path.name}: name must be {path.stem!r}")
        if r["access"] not in CLAUDE_TOOLS or r["kind"] not in ("team", "advisor"):
            raise ValueError(f"{path.name}: bad access or kind")
        roles.append(r)
    return roles


def expected(plugin: Path = PLUGIN) -> dict[Path, str]:
    models = s2s_yaml.load(plugin / "models.yaml")
    files: dict[Path, str] = {}
    for r in load_roles(plugin):
        base = plugin / "agents" if r["enabled"] else plugin / "templates" / "agents-optional"
        files[base / "claude" / f"{r['name']}.md"] = claude_md(r, models)
        files[base / "codex" / f"{r['name']}.toml"] = codex_toml(r, models)
    return files


def generated_dirs(plugin: Path = PLUGIN) -> list[Path]:
    return [plugin / "agents" / "claude", plugin / "agents" / "codex",
            plugin / "templates" / "agents-optional" / "claude", plugin / "templates" / "agents-optional" / "codex"]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--plugin", type=Path, default=PLUGIN)
    args = ap.parse_args(argv)
    want = expected(args.plugin)
    stale = [p for d in generated_dirs(args.plugin) if d.is_dir() for p in d.iterdir()
             if p.is_file() and p not in want]
    if args.check:
        bad = [p for p, text in want.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
        for p in bad + stale:
            print(f"drift: {p.relative_to(args.plugin).as_posix()} does not match roles/; run scripts/sync_agents.py")
        print("agents: FAILED" if bad or stale else f"agents: OK ({len(want)} files)")
        return 1 if bad or stale else 0
    for p in stale:
        p.unlink()
    for p, text in want.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(want)} agent files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
