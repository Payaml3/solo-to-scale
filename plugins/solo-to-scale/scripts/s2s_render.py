"""Render the plugin's templates into a startup's repo. Standard library only.

Ownership decides what each command may touch:
  plugin   rendered by init, re-rendered by upgrade (tools, protocol, standards, workflows, Codex roles)
  section  AGENTS.md and CLAUDE.md: only the block between the solo-to-scale markers is plugin-owned
  founder  written once by init when missing, never touched again (status, registers, context, brand...)
Nothing existing is ever overwritten by init: a differing file becomes a merge proposal.
"""
from __future__ import annotations

import difflib
import fnmatch
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

PLUGIN = Path(__file__).resolve().parents[1]
TEMPLATES = PLUGIN / "templates"
BEGIN, END = "<!-- solo-to-scale:begin", "<!-- solo-to-scale:end -->"
PLACEHOLDER = re.compile(r"(?<!\$)\{\{\s*([A-Za-z0-9_.-]+)\s*\}\}")  # ${{ }} is GitHub Actions syntax
GENERATED_HEADER = "Generated by solo-to-scale"

PLUGIN_OWNED = [
    "founder/operating-protocol.md", "founder/claude-project/*", "founder/.solo-to-scale-version",
    "docs/engineering-standards.md", "tools/*", "tools/tests/*", ".github/workflows/*",
    ".github/ISSUE_TEMPLATE/*", ".claude/statusline.py", ".codex/agents/*", ".claude/agents/*",
]
SECTIONED = ["AGENTS.md", "CLAUDE.md"]
FOUNDER_OWNED = [
    "HANDOFF.md", "Makefile", "founder/project.json", "founder/status.md", "founder/decisions.md",
    "founder/business-context.md", "founder/brand.md", "founder/playbook.md", "founder/team.md",
    "founder/artifacts.md", "founder/slices.json", "founder/gates.json", "founder/heartbeats.json", "founder/dashboard.json", "founder/portfolio.json", "founder/sources/README.md", "founder/board/README.md",
    ".claude/governance.json", ".claude/settings.json", ".codex/config.toml",
]
NOT_RENDERED = ["views/*", "agents-optional/*"]
ROLES = ["chief-of-staff", "research", "product", "architect", "engineer", "qa", "growth", "board"]


def owner(rel: str) -> str:
    def match(pats: list[str]) -> bool:
        return any(fnmatch.fnmatch(rel, p) for p in pats)
    if rel in SECTIONED:
        return "section"
    if match(PLUGIN_OWNED):
        return "plugin"
    if match(FOUNDER_OWNED):
        return "founder"
    raise ValueError(f"template {rel} has no owner; add it to s2s_render.py")


def plugin_version() -> str:
    return json.loads((PLUGIN / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))["version"]


def flatten(ctx: dict[str, Any], prefix: str = "") -> dict[str, Any]:
    out: dict[str, Any] = {}
    for k, v in ctx.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(flatten(v, key + "."))
        else:
            out[key] = v
    return out


INCLUDE = re.compile(r"^\{\{include:([A-Za-z0-9_.-]+)\}\}\n", re.M)


def render_text(text: str, ctx: dict[str, Any], rel: str) -> str:
    text = INCLUDE.sub(lambda m: (PLUGIN / m.group(1)).read_text(encoding="utf-8"), text)
    flat = flatten(ctx)
    is_json = rel.endswith(".json")

    def sub(m: re.Match) -> str:
        key = m.group(1)
        if key not in flat:
            raise KeyError(f"{rel}: no value for {{{{{key}}}}}")
        v = flat[key]
        if isinstance(v, bool):
            return "true" if v else "false"
        if is_json and isinstance(v, str):
            return json.dumps(v)[1:-1]
        return str(v)

    return PLACEHOLDER.sub(sub, text)


def context(answers: dict[str, Any], today: str) -> dict[str, Any]:
    """The render context from init's answers (or upgrade's reconstruction of them)."""
    p = dict(answers.get("project") or {})
    for k in ("name", "repo", "one_line"):
        if not str(p.get(k) or "").strip():
            raise ValueError(f"project.{k} is required (init asks for it)")
    p["working_name"] = bool(p.get("working_name"))
    p["stage"] = int(p.get("stage") or 1)
    p["name_status"] = "working name" if p["working_name"] else "chosen"
    gov = json.loads((TEMPLATES / ".claude" / "governance.json").read_text(encoding="utf-8"))
    gov.update(answers.get("guard") or {})
    budgets = {r: (answers.get("budgets") or {}).get(r, "Open (founder sets it)") for r in ROLES}
    epics = {"architect": "Open (init proposes foundation, operations and audit epics)",
             "qa": "Open (evaluation and test epics)", "growth": "Open (website, docs and SDK epics)",
             "engineer": "all other epics"}
    epics.update(answers.get("epics") or {})
    return {"project": p, "today": today, "plugin": {"version": plugin_version()}, "gov": gov,
            "budget": budgets, "epics": epics,
            "sales_advisor": "enabled" if answers.get("sales_advisor") else "off; init asks whether to enable it at stage 20"}


def templates(answers: dict[str, Any]) -> dict[str, Path]:
    """Destination path -> source file, for everything init writes."""
    out: dict[str, Path] = {}
    for src in sorted(TEMPLATES.rglob("*")):
        if not src.is_file() or "__pycache__" in src.parts:
            continue
        rel = src.relative_to(TEMPLATES).as_posix()
        if any(fnmatch.fnmatch(rel, p) for p in NOT_RENDERED):
            continue
        if rel.endswith("cross-review.yml") and not answers.get("cross_review"):
            continue
        out[rel] = src
    for src in sorted((PLUGIN / "agents" / "codex").glob("*.toml")):
        out[f".codex/agents/{src.name}"] = src
    if answers.get("sales_advisor"):
        out[".claude/agents/sales-advisor.md"] = TEMPLATES / "agents-optional" / "claude" / "sales-advisor.md"
        out[".codex/agents/sales-advisor.toml"] = TEMPLATES / "agents-optional" / "codex" / "sales-advisor.toml"
    return out


def customise(rel: str, text: str, answers: dict[str, Any]) -> str:
    """Answer-driven edits that a placeholder can't express."""
    if rel == ".claude/settings.json":
        data = json.loads(text)
        for plugin_id in answers.get("enable_plugins") or []:
            data["enabledPlugins"][plugin_id] = True
        return json.dumps(data, indent=2) + "\n"
    if rel == ".claude/governance.json":
        data = json.loads(text)
        data.update(answers.get("guard") or {})
        return json.dumps(data, indent=2) + "\n"
    if rel == "founder/heartbeats.json":
        data = json.loads(text)
        for role, cfg in data["roles"].items():
            cfg["monthly_budget_usd"] = usd((answers.get("budgets") or {}).get(role))
        return json.dumps(data, indent=2) + "\n"
    if rel == "founder/playbook.md":
        stage = int((answers.get("project") or {}).get("stage") or 1)
        return re.sub(rf"^(\| {stage} \|.*\| )To do( \|)$", r"\1Current\2", text, flags=re.M)
    if rel == "founder/.solo-to-scale-version":
        return text + f"rendered-for: {(answers.get('project') or {}).get('name', '')}\n"
    return text


def usd(value: Any) -> float | None:
    """A budget answer ("$40", "40 USD", 40) as a number; anything else is not set."""
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return float(value) if value > 0 else None
    m = re.fullmatch(r"\s*\$?\s*(\d+(?:\.\d+)?)\s*(?:USD|usd|\$)?\s*(?:/\s*month)?\s*", str(value or ""))
    return float(m.group(1)) if m and float(m.group(1)) > 0 else None


def render_all(answers: dict[str, Any], today: str) -> dict[str, str]:
    ctx = context(answers, today)
    out = {}
    for rel, src in templates(answers).items():
        text = src.read_text(encoding="utf-8")
        out[rel] = customise(rel, render_text(text, ctx, rel), answers)
    return out


def section(text: str) -> str | None:
    i, j = text.find(BEGIN), text.find(END)
    return text[i:j + len(END)] if i >= 0 and j > i else None


@dataclass
class Action:
    rel: str
    kind: str  # create | same | update | section | enable | propose | keep
    owner: str
    content: str = ""
    note: str = ""


@dataclass
class Plan:
    actions: list[Action] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def by(self, kind: str) -> list[Action]:
        return [a for a in self.actions if a.kind == kind]

    def summary(self) -> str:
        lines = []
        for kind, label in (("create", "Create"), ("update", "Update (plugin-owned)"), ("section", "Update the plugin block"),
                            ("enable", "Enable the plugin (only its two entries added; everything else kept)"),
                            ("propose", "Exists and differs: merge proposed in the PR"), ("keep", "Founder-owned: left alone"),
                            ("same", "Already current")):
            items = self.by(kind)
            if items:
                lines.append(f"{label} ({len(items)}):")
                lines += [f"  - {a.rel}" + (f"  ({a.note})" if a.note else "") for a in items]
        lines += self.notes
        return "\n".join(lines)


def diff(rel: str, old: str, new: str, limit: int = 60) -> str:
    d = list(difflib.unified_diff(old.splitlines(), new.splitlines(), f"a/{rel}", f"b/{rel}", lineterm=""))
    return "\n".join(d[:limit] + ([f"... ({len(d) - limit} more diff lines)"] if len(d) > limit else []))


def proposal_text(plan: Plan, title: str) -> str:
    """The merge proposals for the PR description."""
    out = [f"## {title}", "", "Files that already exist are never overwritten. For each one, the change below is a proposal to merge by hand.", ""]
    for a in plan.by("propose"):
        out += [f"### `{a.rel}`", a.note, "", "```diff", a.content, "```", ""]
    return "\n".join(out) if plan.by("propose") else ""


def merged_json(old: str, new: str) -> str | None:
    """For JSON settings, suggest the existing file plus our missing keys."""
    try:
        o, n = json.loads(old), json.loads(new)
    except ValueError:
        return None

    def merge(a: Any, b: Any) -> Any:
        if isinstance(a, dict) and isinstance(b, dict):
            res = dict(a)
            for k, v in b.items():
                res[k] = merge(a[k], v) if k in a else v
            return res
        if isinstance(a, list) and isinstance(b, list):
            return a + [x for x in b if x not in a]
        return a
    return json.dumps(merge(o, n), indent=2) + "\n"


